"""Build artifacts/final_results.md and final_results.json from frozen eval outputs."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

FINAL = ROOT / "artifacts" / "general_eval" / "final"
OUT_MD = ROOT / "artifacts" / "final_results.md"
OUT_JSON = ROOT / "artifacts" / "final_results.json"
OUT_TEX = ROOT / "docs" / "paper" / "final_tables.tex"
DATASETS = ("synthetic", "heldout", "timeqa")
SYSTEMS = (
    "B1_llm_only",
    "B2_standard_rag",
    "B3_fixed_temporal",
    "tempralm_decay",
    "adaptive",
    "adaptive_fast",
)
LABELS = {
    "B1_llm_only": "B1 no retrieval",
    "B2_standard_rag": "B2 standard",
    "B3_fixed_temporal": "B3 fixed ±2y",
    "tempralm_decay": "B4 TempRALM decay",
    "adaptive": "Adaptive",
    "adaptive_fast": "Adaptive-Fast (sufficiency off)",
}
ABLATION_LABELS = {
    "adaptive_router_off": "router off (always retrieve)",
    "adaptive_window_off": "adaptive window off (fixed ±2y)",
    "adaptive_sufficiency_off": "sufficiency loop off",
    "adaptive_entity_cut_off": "surname/entity cut off",
    "adaptive_sentence_selector_off": "sentence selector off",
}
METRICS = (
    "n",
    "em",
    "token_f1",
    "contains",
    "precision_at_k",
    "recall_at_k",
    "temporal_acc",
    "retrieval_rate",
    "latency_s",
    "latency_s_median",
)


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt(value, key: str) -> str:
    if value is None or (isinstance(value, float) and value != value):
        return "—"
    if key == "n":
        return str(int(value))
    if key in ("retrieval_rate",):
        return f"{value:.3f}"
    if key.startswith("latency"):
        return f"{value:.3f}"
    return f"{value:.3f}"


def _row(system: str, metrics: dict) -> str:
    cells = [_fmt(metrics.get(k), k) for k in METRICS]
    return "| " + " | ".join([LABELS.get(system, system), *cells]) + " |"


def _tex_cell(value, key: str) -> str:
    text = _fmt(value, key)
    if text == "—":
        return "---"
    return text


def _tex_label(label: str) -> str:
    short = {
        "B4 TempRALM decay": "B4 decay",
        "Adaptive-Fast (sufficiency off)": "Adaptive-Fast",
    }
    return short.get(label, label).replace("±", r"$\pm$")


def _tex_tables(payload: dict) -> str:
    chunks = [
        "% Auto-generated by scripts/compile_final_results.py. Do not edit by hand.",
        "",
    ]
    for dataset in DATASETS:
        summary = payload["datasets"].get(dataset) or {}
        if not summary:
            continue
        n = int(next(iter(summary.values())).get("n", 0))
        label = {"synthetic": "tab:syn77", "heldout": "tab:held193", "timeqa": "tab:timeqa500"}[dataset]
        title = {
            "synthetic": f"Frozen Checkpoint B. Templated test, $n{{=}}{n}$. EM is exact match, F1 is token F1, Cont is containment, P@5 and R@5 use gold document ids, Temp is the timestamp metric, Ret is retrieval rate, mean $s$ and med $s$ are seconds.",
            "heldout": f"Frozen Checkpoint B. Questions naming six entities, $n{{=}}{n}$. Columns match Table~\\ref{{tab:syn77}}.",
            "timeqa": f"Frozen Checkpoint B. TimeQA test, $n{{=}}{n}$. EM and F1 use a span extracted from the selected sentence; Cont uses the sentence. Temp is omitted.",
        }[dataset]
        chunks.append("\\begin{table*}[t]")
        chunks.append("\\centering")
        chunks.append(f"\\caption{{{title}}}")
        chunks.append(f"\\label{{{label}}}")
        chunks.append("\\small")
        chunks.append("\\begin{tabular}{lccccccccc}")
        chunks.append("\\toprule")
        chunks.append("System & EM & F1 & Cont & P@5 & R@5 & Temp & Ret & mean $s$ & med $s$ \\\\")
        chunks.append("\\midrule")
        for system in SYSTEMS:
            if system not in summary:
                continue
            m = summary[system]
            cells = [
                _tex_label(LABELS.get(system, system)),
                _tex_cell(m.get("em"), "em"),
                _tex_cell(m.get("token_f1"), "token_f1"),
                _tex_cell(m.get("contains"), "contains"),
                _tex_cell(m.get("precision_at_k"), "precision_at_k"),
                _tex_cell(m.get("recall_at_k"), "recall_at_k"),
                _tex_cell(m.get("temporal_acc"), "temporal_acc"),
                _tex_cell(m.get("retrieval_rate"), "retrieval_rate"),
                _tex_cell(m.get("latency_s"), "latency_s"),
                _tex_cell(m.get("latency_s_median"), "latency_s_median"),
            ]
            chunks.append(" & ".join(cells) + " \\\\")
        chunks.append("\\bottomrule")
        chunks.append("\\end{tabular}")
        chunks.append("\\end{table*}")
        chunks.append("")
    chunks.append("\\begin{table*}[t]")
    chunks.append("\\centering")
    chunks.append(
        "\\caption{Ablations of Adaptive on the frozen configuration. Each row turns off one component.}"
    )
    chunks.append("\\label{tab:ablations}")
    chunks.append("\\small")
    chunks.append("\\begin{tabular}{llccccc}")
    chunks.append("\\toprule")
    chunks.append("Data & Ablation & EM & F1 & Cont & Ret & med $s$ \\\\")
    chunks.append("\\midrule")
    first_ds = True
    for dataset in DATASETS:
        if not first_ds:
            chunks.append("\\midrule")
        first_ds = False
        full = payload["datasets"].get(dataset, {}).get("adaptive")
        n_rows = 1 + len(ABLATION_LABELS)
        if full:
            chunks.append(
                f"\\multirow{{{n_rows}}}{{*}}{{{dataset}}} & Adaptive (full) & "
                f"{_tex_cell(full.get('em'), 'em')} & {_tex_cell(full.get('token_f1'), 'token_f1')} & "
                f"{_tex_cell(full.get('contains'), 'contains')} & {_tex_cell(full.get('retrieval_rate'), 'retrieval_rate')} & "
                f"{_tex_cell(full.get('latency_s_median'), 'latency_s_median')} \\\\"
            )
        for key, label in ABLATION_LABELS.items():
            summary = payload.get("ablations", {}).get(dataset, {}).get(key)
            if not summary:
                chunks.append(
                    f" & {_tex_label(label)} & --- & --- & --- & --- & --- \\\\"
                )
                continue
            metrics = summary.get(key) or next(iter(summary.values()))
            chunks.append(
                f" & {_tex_label(label)} & {_tex_cell(metrics.get('em'), 'em')} & "
                f"{_tex_cell(metrics.get('token_f1'), 'token_f1')} & "
                f"{_tex_cell(metrics.get('contains'), 'contains')} & "
                f"{_tex_cell(metrics.get('retrieval_rate'), 'retrieval_rate')} & "
                f"{_tex_cell(metrics.get('latency_s_median'), 'latency_s_median')} \\\\"
            )
    chunks.append("\\bottomrule")
    chunks.append("\\end{tabular}")
    chunks.append("\\end{table*}")
    chunks.append("")
    return "\n".join(chunks)


def main() -> None:
    payload = {"config": "configs/final.yaml", "datasets": {}, "ablations": {}}
    lines = [
        "# Frozen Checkpoint B results",
        "",
        "Source: `artifacts/general_eval/final/`. Config: `configs/final.yaml`.",
        "B1/B2/B3/B4/Adaptive share the extractive reader, answer projection, entity/surname cut, and sentence selector.",
        "B1–B3 and Adaptive differ on retrieval decision, the time window, and the sufficiency loop.",
        "B4 is dense+BM25 with exponential year-distance decay (lambda 2 years), no hard window and no sufficiency loop.",
        "Adaptive-Fast is the saved sufficiency-off ablation, not a new four-system run. Its latency is from that later Adaptive-only run.",
        "Learned path is experimental and is not in these tables.",
        "TimeQA EM/F1 use span extraction on the selected sentence; Contains still uses the sentence.",
        "Temporal accuracy is omitted for TimeQA (index timestamps are not fact dates).",
        "",
        "## Master table",
        "",
        "| Dataset | System | N | EM | F1 | Contains | P@5 | R@5 | Temp | Ret | mean s | median s |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    dataset_blocks: list[str] = []
    for dataset in DATASETS:
        summary_path = FINAL / dataset / "results_summary.json"
        if not summary_path.exists():
            dataset_blocks.append(f"## {dataset}: missing `{summary_path}`")
            dataset_blocks.append("")
            continue
        summary = _load(summary_path)
        b4_path = FINAL / dataset / "b4_tempralm_decay" / "results_summary.json"
        if b4_path.exists():
            b4 = _load(b4_path)
            summary["tempralm_decay"] = b4.get("tempralm_decay") or next(iter(b4.values()))
        fast_path = FINAL / "ablations" / dataset / "results_sufficiency_off_summary.json"
        if fast_path.exists():
            fast = _load(fast_path)
            summary["adaptive_fast"] = fast.get("adaptive_sufficiency_off") or next(iter(fast.values()))
            summary["adaptive_fast"] = dict(summary["adaptive_fast"])
            summary["adaptive_fast"]["note"] = (
                "ablation-derived variant: sufficiency loop off; latency is from the ablation run"
            )
        payload["datasets"][dataset] = summary
        n = int(next(iter(summary.values())).get("n", 0)) if summary else 0
        dataset_blocks.append(f"## {dataset} (n={n})")
        dataset_blocks.append("")
        dataset_blocks.append(
            "| System | N | EM | F1 | Contains | P@5 | R@5 | Temp | Ret | mean s | median s |"
        )
        dataset_blocks.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        for system in SYSTEMS:
            if system not in summary:
                continue
            metrics = summary[system]
            dataset_blocks.append(_row(system, metrics))
            cells = [_fmt(metrics.get(k), k) for k in METRICS]
            lines.append("| " + " | ".join([dataset, LABELS.get(system, system), *cells]) + " |")
        dataset_blocks.append("")
        dataset_blocks.append(f"File: `{summary_path.relative_to(ROOT)}`")
        dataset_blocks.append("")
    lines.append("")
    lines.extend(dataset_blocks)

    lines.append("## Ablations (Adaptive only)")
    lines.append("")
    lines.append(
        "Each ablation turns off one Adaptive component. Baselines are not re-run here."
    )
    lines.append("")
    for dataset in DATASETS:
        lines.append(f"### {dataset}")
        lines.append("")
        lines.append(
            "| Ablation | N | EM | F1 | Contains | P@5 | R@5 | Temp | Ret | mean s | median s |"
        )
        lines.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
        payload["ablations"][dataset] = {}
        full = payload["datasets"].get("adaptive") if False else payload["datasets"].get(dataset, {}).get("adaptive")
        if full:
            lines.append(_row("adaptive", full).replace("Adaptive", "Adaptive (full)"))
        for key, label in ABLATION_LABELS.items():
            path = FINAL / "ablations" / dataset / f"results_{key.replace('adaptive_', '')}_summary.json"
            alt = FINAL / "ablations" / dataset / f"results_{key[len('adaptive_'):]}_summary.json"
            summary_path = path if path.exists() else alt
            if not summary_path.exists():
                # evaluate.py writes results_{ablation}_summary.json with ablation name without prefix
                stem = key.replace("adaptive_", "")
                summary_path = FINAL / "ablations" / dataset / f"results_{stem}_summary.json"
            if not summary_path.exists():
                lines.append(f"| {label} | — | — | — | — | — | — | — | — | — | — |")
                continue
            summary = _load(summary_path)
            payload["ablations"][dataset][key] = summary
            metrics = summary.get(key) or next(iter(summary.values()))
            cells = [_fmt(metrics.get(k), k) for k in METRICS]
            lines.append("| " + " | ".join([label, *cells]) + " |")
        lines.append("")

    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    OUT_JSON.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text(_tex_tables(payload), encoding="utf-8")
    print("Wrote", OUT_MD)
    print("Wrote", OUT_JSON)
    print("Wrote", OUT_TEX)
    sig_path = ROOT / "artifacts" / "significance.json"
    if sig_path.exists():
        from scripts.compute_significance import _append_md, _markdown

        _append_md(_markdown(json.loads(sig_path.read_text(encoding="utf-8"))))
        print("Appended significance section")


if __name__ == "__main__":
    main()
